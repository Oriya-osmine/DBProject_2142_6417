-- Create a new separate schema for mapping tables
CREATE SCHEMA IF NOT EXISTS mappings;

-- Link table between local kitchen stations and partner menu items
-- Uses: order routing, station-level inventory checks, preparation routing
CREATE TABLE mappings.station_menu_item_link (
    link_id SERIAL PRIMARY KEY, -- Unique link identifier
    local_station_id INT NOT NULL REFERENCES public.kitchen_station(station_id), -- Reference to the local kitchen station
    menu_item_id INT NOT NULL REFERENCES partners.menu_item(menu_item_id), -- Reference to the partner's menu item table
    is_active BOOLEAN DEFAULT TRUE, -- Link active status flag
    CONSTRAINT station_menu_item_unique UNIQUE (local_station_id, menu_item_id) -- Prevent duplicate links for the same station and item
);







